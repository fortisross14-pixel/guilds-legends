function cells(rows) {
  const rects = [];
  rows.forEach((row, y) => {
    let x = 0;
    while (x < row.length) {
      if (row[x] !== '#') {
        x += 1;
        continue;
      }
      let end = x;
      while (row[end] === '#') end += 1;
      rects.push(`M${x} ${y}h${end - x}v1h${x - end}z`);
      x = end;
    }
  });
  return rects.join('');
}

const PATHS = Object.fromEntries(Object.entries(ICONS).map(([name, rows]) => [name, cells(rows)]));

/** A crisp pixel icon. `size` should be a multiple of 12 (12, 24, 36, 48). */
export default function PixelIcon({ name, size = 24, label = undefined, className = '' }) {
  const d = PATHS[name];
  if (!d) return null;
  return (
    <svg
      className={`pixel-icon ${className}`}
      width={size}
      height={size}
      viewBox="0 0 12 12"
      shapeRendering="crispEdges"
      role={label ? 'img' : undefined}
      aria-label={label}
      aria-hidden={label ? undefined : true}
      focusable="false"
    >
      <path d={d} fill="currentColor" />
    </svg>
  );
}

